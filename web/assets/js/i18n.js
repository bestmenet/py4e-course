export function currentLanguage() {
  try { return localStorage.getItem('py4e:language') === 'en' ? 'en' : 'zh'; } catch { return 'zh'; }
}

export function t(text, vars = {}) {
  const source = String(text);
  const normalized = source.trim().replace(/\s+/g, ' ');
  const key = Object.hasOwn(ZH, source) ? source : normalized;
  const value = currentLanguage() === 'zh' && Object.hasOwn(ZH, key) ? ZH[key] : text;
  return String(value).replace(/\{(\w+)\}/g, (_, key) => vars[key] ?? `{${key}}`);
}

export function setLanguage(language) {
  const next = language === 'zh' ? 'zh' : 'en';
  try { localStorage.setItem('py4e:language', next); } catch { /* private mode */ }
  document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en';
  window.location.reload();
}
